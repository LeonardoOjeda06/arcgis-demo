CREATE TABLE ME_CLIENT_APP (
  ID                NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CLIENT_ID         VARCHAR2(64)  NOT NULL,
  NAME              VARCHAR2(150) NOT NULL,
  SECRET_HASH       VARCHAR2(255) NOT NULL,
  STATUS            VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  SECRET_ROTATED_AT TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_AT        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP,
  CONSTRAINT UQ_ME_APP_CLIENT_ID UNIQUE (CLIENT_ID),
  CONSTRAINT CK_ME_APP_STATUS CHECK (STATUS IN ('ACTIVE','DISABLED'))
);

CREATE TABLE ME_CLIENT_ORIGIN (
  ID             NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CLIENT_APP_ID  NUMBER NOT NULL,
  ORIGIN         VARCHAR2(255) NOT NULL,   -- ej. https://portal.cliente.gov.co (sin / final)
  CONSTRAINT FK_ME_ORIGIN_APP FOREIGN KEY (CLIENT_APP_ID) REFERENCES ME_CLIENT_APP(ID) ON DELETE CASCADE,
  CONSTRAINT UQ_ME_ORIGIN UNIQUE (CLIENT_APP_ID, ORIGIN),
  CONSTRAINT CK_ME_ORIGIN_HTTPS CHECK (
    ORIGIN LIKE 'https://%' OR ORIGIN LIKE 'http://localhost%' OR ORIGIN LIKE 'http://127.0.0.1%'
  )
);

CREATE TABLE ME_PERMISSION (
  CODE         VARCHAR2(50)  PRIMARY KEY,
  DESCRIPTION  VARCHAR2(200) NOT NULL
);

CREATE TABLE ME_CLIENT_PERMISSION (
  CLIENT_APP_ID    NUMBER       NOT NULL,
  PERMISSION_CODE  VARCHAR2(50) NOT NULL,
  CONSTRAINT PK_ME_CLIENT_PERM PRIMARY KEY (CLIENT_APP_ID, PERMISSION_CODE),
  CONSTRAINT FK_ME_CP_APP  FOREIGN KEY (CLIENT_APP_ID)   REFERENCES ME_CLIENT_APP(ID) ON DELETE CASCADE,
  CONSTRAINT FK_ME_CP_PERM FOREIGN KEY (PERMISSION_CODE) REFERENCES ME_PERMISSION(CODE)
);

CREATE TABLE ME_SAVED_LOCATION (
  ID                NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CLIENT_APP_ID     NUMBER        NOT NULL,
  EXTERNAL_USER_ID  VARCHAR2(100) NOT NULL,   -- identificador opaco que da la app cliente
  LABEL             VARCHAR2(100),
  ADDRESS           VARCHAR2(250) NOT NULL,
  LATITUDE          NUMBER(9,6)   NOT NULL,
  LONGITUDE         NUMBER(9,6)   NOT NULL,
  CREATED_AT        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  DELETED_AT        TIMESTAMP,                -- borrado lógico
  CONSTRAINT FK_ME_LOC_APP FOREIGN KEY (CLIENT_APP_ID) REFERENCES ME_CLIENT_APP(ID),
  CONSTRAINT CK_ME_LOC_LAT CHECK (LATITUDE  BETWEEN -90  AND 90),
  CONSTRAINT CK_ME_LOC_LNG CHECK (LONGITUDE BETWEEN -180 AND 180)
);
CREATE INDEX IX_ME_LOC_OWNER ON ME_SAVED_LOCATION (CLIENT_APP_ID, EXTERNAL_USER_ID);

CREATE TABLE ME_AUDIT_LOG (
  ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ACTOR_TYPE  VARCHAR2(10)   NOT NULL,   -- ADMIN | CLIENT | SYSTEM
  ACTOR_ID    VARCHAR2(100)  NOT NULL,
  ACTION      VARCHAR2(50)   NOT NULL,   -- ej. PERMISSIONS_UPDATED
  TARGET      VARCHAR2(100),
  DETAIL      VARCHAR2(1000),            -- JSON corto, SIN datos personales
  IP          VARCHAR2(45),
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_ME_AUDIT_CREATED ON ME_AUDIT_LOG (CREATED_AT);

